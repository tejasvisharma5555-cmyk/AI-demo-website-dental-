#!/usr/bin/env python3
"""Detect which pages of a platform's docs changed since the last research run.

Usage:
  docs-diff.py <platform> <llms-full.txt URL or local path> [--save]

Splits the full docs dump into pages (each page has a "Source: <url>" line),
hashes every page, and compares with docs/platforms/<platform>/page-hashes.tsv.

Prints ADDED / CHANGED / REMOVED page paths.
Exit 0  = nothing changed (skip research)
Exit 10 = something changed or never researched (research those pages)
--save  = write the current hashes to page-hashes.tsv (run after /docs is updated)
"""
import hashlib
import os
import re
import subprocess
import sys
import urllib.request


def main() -> int:
    args = [a for a in sys.argv[1:] if a != "--save"]
    save = "--save" in sys.argv
    if len(args) != 2:
        print(__doc__)
        return 2
    platform, src = args
    root = subprocess.check_output(["git", "rev-parse", "--show-toplevel"], text=True).strip()
    tsv = os.path.join(root, "docs", "platforms", platform, "page-hashes.tsv")

    if src.startswith("http"):
        with urllib.request.urlopen(src) as r:
            text = r.read().decode("utf-8", "replace")
    else:
        with open(src, encoding="utf-8") as f:
            text = f.read()

    pages = {}
    for chunk in re.split(r"\n(?=# [^\n]+\nSource: )", text):
        m = re.search(r"^Source: (\S+)", chunk, flags=re.M)
        if m:
            pages[m.group(1)] = hashlib.sha256(chunk.encode()).hexdigest()[:16]

    old = {}
    if os.path.exists(tsv):
        with open(tsv, encoding="utf-8") as f:
            for line in f:
                if line.strip() and not line.startswith("#"):
                    url, h = line.rstrip("\n").split("\t")
                    old[url] = h

    added = sorted(set(pages) - set(old))
    removed = sorted(set(old) - set(pages))
    changed = sorted(u for u in pages if u in old and pages[u] != old[u])

    for label, items in (("ADDED", added), ("CHANGED", changed), ("REMOVED", removed)):
        for u in items:
            print(f"{label}\t{u}")
    print(f"pages={len(pages)} added={len(added)} changed={len(changed)} removed={len(removed)}")

    if save:
        os.makedirs(os.path.dirname(tsv), exist_ok=True)
        with open(tsv, "w", encoding="utf-8") as f:
            f.write("# page_url\tsha256_16 — generated by research-voice-platform/scripts/docs-diff.py\n")
            for u in sorted(pages):
                f.write(f"{u}\t{pages[u]}\n")
        print(f"saved {tsv}")

    return 10 if (added or changed or removed) else 0


if __name__ == "__main__":
    sys.exit(main())
